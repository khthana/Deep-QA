from harness import main

FILES = {
    'dialog': 'frontend/src/components/ConfirmDialog.js',
}

FOCUS_EFFECT = (
    '  useEffect(() => {\n'
    '    if (open) box.current.focus()\n'
    '  }, [open])\n'
)

ESCAPE_EFFECT = (
    '  useEffect(() => {\n'
    '    if (!open) return undefined\n'
    '    const onKeyDown = event => {\n'
    "      if (event.key === 'Escape') onCancel()\n"
    '    }\n'
    "    window.addEventListener('keydown', onKeyDown)\n"
    "    return () => window.removeEventListener('keydown', onKeyDown)\n"
    '  }, [open, onCancel])\n'
    '\n'
)

MUTANTS = {
    # กล่องกลับไปเป็น div ที่ไม่มีบทบาท ซึ่งคือสิ่งที่มันเป็นก่อน #204
    'norole': ('dialog',
        '        ref={box}\n'
        '        role="dialog"\n',
        '        ref={box}\n'),
    # บทบาทยังอยู่ แต่ไม่ขอให้ใครหยุดอ่านนอกกล่อง — ข้ออ้างที่สองของแถว 1 ไม่ใช่ข้ออ้างแรก
    'notmodal': ('dialog',
        '        aria-modal="true"\n',
        '        aria-modal="false"\n'),
    # ชื่อที่เข้าถึงได้หายไป หัวเรื่องยังวาดอยู่บนจอ
    'noname': ('dialog',
        '        aria-labelledby={titleId}\n',
        ''),
    # คำบรรยายหายไป ประโยคยังวาดอยู่บนจอ
    'nodescription': ('dialog',
        '        aria-describedby={messageId}\n',
        ''),
    # พฤติกรรมก่อน #204: โฟกัสค้างที่ปุ่มของแถวที่เปิดกล่องมา
    'nofocusonopen': ('dialog', FOCUS_EFFECT + '\n', ''),
    # พฤติกรรมก่อน #204: ไม่มีทางปิดกล่องด้วยแป้นพิมพ์
    'noescape': ('dialog', ESCAPE_EFFECT, ''),
    # ข้อเสนอที่ถูกเลื่อน เขียนให้รันได้ (#48) — focus trap ที่ตั๋วเสนอเป็นทาง 1
    'trapsfocus': ('dialog', FOCUS_EFFECT,
        FOCUS_EFFECT +
        '\n'
        '  useEffect(() => {\n'
        '    if (!open) return undefined\n'
        '    const keep = event => {\n'
        '      if (!box.current.contains(event.target)) box.current.focus()\n'
        '    }\n'
        "    document.addEventListener('focusin', keep)\n"
        "    return () => document.removeEventListener('focusin', keep)\n"
        '  }, [open])\n'),
}

main(FILES, MUTANTS)
